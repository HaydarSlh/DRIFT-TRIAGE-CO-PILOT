async def _postgres_reachable() -> bool:
    try:
        engine = create_async_engine(POSTGRES_ADMIN_URL, isolation_level="AUTOCOMMIT")
        async with engine.connect() as conn:
            await conn.execute(text("SELECT 1"))
        await engine.dispose()
        return True
    except Exception:
        return False


