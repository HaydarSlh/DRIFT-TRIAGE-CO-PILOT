def _default_fake() -> FakeChatModel:
    """Build a FakeChatModel that drives a full graph run end-to-end."""
    happy_report = (
        "# fake topic\n\n"
        "A short fake introduction generated by the test fake LLM.\n\n"
        "## Findings\n\n"
        "### F1\nFake summary one used in tests.\n\n"
        "### F2\nFake summary two used in tests.\n\n"
        "## Limitations\n\n"
        "Fake limitations section. The fake LLM does not generate real content. "
        "These extra words pad the report so any downstream length check passes."
    )
    fake = FakeChatModel(
        by_schema={
            ResearchOutput: ResearchOutput(
                findings=[
                    Finding(title="F1", summary="s1", confidence=0.9, source_hint="src1"),
                    Finding(title="F2", summary="s2", confidence=0.7, source_hint="src2"),
                    Finding(title="F3", summary="s3", confidence=0.5, source_hint="src3"),
                ]
            ),
        },
        responses=[
            # Critic + writer each call .ainvoke once per supervisor cycle. The
            # supervisor's structured-output calls are handled by ``by_schema``.
            happy_report,
            happy_report,
            happy_report,
            happy_report,
            happy_report,
            happy_report,
        ],
    )
    # Add the supervisor decisions as an ordered list keyed by schema. The
    # FakeChatModel's by_schema accepts a callable later if we want, but for
    # now we hand-roll an iterator via repeated entries.
    sup_seq = ["researcher", "critic", "writer", "done"]
    decisions = [
        SupervisorDecision(next_agent=n, reasoning="fake")  # type: ignore[arg-type]
        for n in sup_seq
    ]
    # Patch the schema-map to use a stateful iterator wrapper.
    fake._by_schema[SupervisorDecision] = _SequenceCycler(decisions)  # type: ignore[assignment]
    return fake


class _SequenceCycler:
    """Wraps a sequence so the FakeChatModel emits one item per invocation.

    Returned via ``by_schema`` — the dispatcher detects it via ``__iter__``
    being one-shot and pulls the next value.
    """

    def __init__(self, values: list[Any]) -> None:
        self._values = values
        self._cursor = 0

    def next(self) -> Any:
        if self._cursor >= len(self._values):
            return self._values[-1]
        v = self._values[self._cursor]
        self._cursor += 1
        return v


# Wire the cycler into FakeChatModel.dispatch by monkey-patching at fixture
# setup time. This keeps ``fakes.py`` clean of test-only branches.

_ORIGINAL_DISPATCH = FakeChatModel._dispatch


async def _cycler_aware_dispatch(self, *, messages, schema, kwargs):  # type: ignore[no-untyped-def]
    """Duck-type any value with a callable ``.next`` as a per-call cycler.

    Tests in different files define their own tiny cycler classes; we don't
    want a registry. If the by_schema entry has ``.next()``, treat it as
    stateful.
    """
    if schema is not None:
        bound = self._by_schema.get(schema)
        if bound is not None and callable(getattr(bound, "next", None)):
            from app.testing.fakes import _CallRecord, _render

            self.call_history.append(
                _CallRecord(
                    messages_repr=_render(messages), schema=schema, kwargs=dict(kwargs)
                )
            )
            return bound.next()
    return await _ORIGINAL_DISPATCH(self, messages=messages, schema=schema, kwargs=kwargs)


FakeChatModel._dispatch = _cycler_aware_dispatch  # type: ignore[assignment]


